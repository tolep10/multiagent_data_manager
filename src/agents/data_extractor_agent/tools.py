from typing import Annotated

from langchain_core.messages import ToolMessage
from psycopg2.extras import RealDictCursor
import json
from langchain_core.tools import tool, InjectedToolCallId
from langgraph.types import Command

from .connection import DBPoolConnection
from .queries import sql_queries_dict


class DataExtractorAgent:
    def __init__(self):
        self._db_pool_connection = DBPoolConnection()



    async def get_db_schema(self) -> str:
        """
        Returns the names of all tables in the database schema along with primary
        and foreign key relationships. Essential for the agent to map the database structure.
        """
        query = sql_queries_dict.get("full_db_tables_info", None)
        if not query:
            return "SYSTEM ERROR: The internal query 'full_db_tables_info' was not found in the configuration."

        conn = None
        pool = None

        try:
            pool = await self._db_pool_connection.get_db_pool()
            conn = pool.getconn()

            with conn.cursor(cursor_factory=RealDictCursor) as cur:
                cur.execute(query)
                rows = cur.fetchall()

                if not rows:
                    return "WARNING: The database schema is completely empty. No tables were found."


                schema_json = json.dumps(rows, default=str, ensure_ascii=False, indent=2)

            return f"SUCCESS: here is the complete database schema:\n```json\n{schema_json}\n```"

        except Exception as e:
            msg_error = f"ERROR retrieving database schema: {str(e)}"
            print(msg_error)
            return msg_error

        finally:
            if conn and pool:
                pool.putconn(conn)



    async def get_table_schema(self, table_name: str) -> str:
        """
        Returns the structure of a specific table (columns, data types, nullability, keys).
        Crucial for the agent to identify available fields before generating a query.
        """
        query = sql_queries_dict.get("full_table_info", None)
        if not query:
            return "SYSTEM ERROR: The internal query 'full_table_info' was not found in the configuration."

        conn = None
        pool = None

        try:
            pool = await self._db_pool_connection.get_db_pool()
            conn = pool.getconn()

            with conn.cursor(cursor_factory=RealDictCursor) as cur:
                cur.execute(query, (table_name,))
                rows = cur.fetchall()

                if not rows:
                    return f"ERROR: The table '{table_name}' does not exist in the database or has no visible columns. Please verify the name using get_db_schema."


                schema_json = json.dumps(rows, default=str, ensure_ascii=False, indent=2)

            return f"SUCCESS: here is the complete database schema:\n```json\n{schema_json}\n```"

        except Exception as e:
            msg_error = f"ERROR retrieving schema for table '{table_name}': {str(e)}"
            print(msg_error)
            return msg_error

        finally:
            if conn and pool:
                pool.putconn(conn)



    async def execute_analytical_query(self, sql: str, tool_call_id: Annotated[str, InjectedToolCallId]) -> Command:
        """
        Executes a read-only SQL query generated by the model. Returns the result set.
        """
        print(sql)
        forbidden_keywords = ["DROP", "DELETE", "UPDATE", "INSERT", "TRUNCATE", "ALTER", "GRANT"]
        if any(keyword in sql.upper() for keyword in forbidden_keywords):
            raise RuntimeError("CRITICAL ERROR: Permission denied. For security reasons, you are ONLY allowed to execute SELECT queries. Please rewrite your query.")

        conn = None
        pool = None

        try:
            pool = await self._db_pool_connection.get_db_pool()
            conn = pool.getconn()

            with conn.cursor(cursor_factory=RealDictCursor) as cur:
                cur.execute(sql)
                rows = cur.fetchall()


            if not rows:
                return Command(
                    update={
                        "extracted_data": [],
                        "progress": {"data_extracted": "The query was executed successfully, but no rows were found in the database for that criterion."},
                        "messages": [
                            ToolMessage(
                                content="The query was executed successfully, but no rows were found in the database for that criterion.",
                                tool_call_id=tool_call_id,
                            )
                        ],
                    }
                )

            print(f"SUCCESS: {len(rows)} rows were extracted from the database.")
            return Command(
                update={
                    "extracted_data": rows,
                    "progress": {"data_extracted": f"SUCCESS ({len(rows)} rows)"},
                    "messages": [
                        ToolMessage(
                            content=f"SUCCESS: {len(rows)} rows were extracted from the database.",
                            tool_call_id=tool_call_id,
                        )
                    ]
                }
            )

        except Exception as e:
            msg_error = f"SQL ERROR: {str(e)}. Please review your table names, column names, and query syntax."
            print(msg_error)
            return Command(
                update={
                    # Limpiamos el estado para que la tool de Excel sepa que no hay datos válidos
                    "extracted_data": None,
                    "progress": {"data_extracted": f"ERROR: Extraction tool failure. Details: {msg_error}"},
                    "messages": [
                        ToolMessage(
                            content=f"ERROR: Extraction tool failure. Details: {msg_error}",
                            tool_call_id=tool_call_id,
                        )
                    ]
                }
            )

        finally:
            if conn and pool:
                pool.putconn(conn)


data_extractor_agent = DataExtractorAgent()

data_extractor_agent_tools = [
    tool(data_extractor_agent.get_db_schema),
    tool(data_extractor_agent.get_table_schema),
    tool(data_extractor_agent.execute_analytical_query),
]